class HandoffBrepVerdictGate(unittest.TestCase):
    """A1 · exit 14. verify.py is the only check that proves step_valid / closed / no_bad_faces on
    the exported solid; nothing automated ran it and it wrote nothing down, so a plate could reach
    approval with its B-rep never checked. verify.sh now records a verdict beside the part and
    handoff.sh refuses without one FOR THESE BYTES.

    Every test here is a mutation of one green plate. Six of them were run by hand against the
    gate as it landed on 2026-09-04 and are the reason for this class: the four record mutations
    all refused, and the two environment ones — UNSTAMPED_OK=1 with no plate_geom.txt, and
    NO_SPEC_OK=1 over a spec-less part — both reached exit 0 with BREP_VERDICT_RESULT: PASS."""

    def setUp(self):
        self.td = tempfile.TemporaryDirectory(); self.addCleanup(self.td.cleanup)
        self.out = os.path.join(self.td.name, "build"); os.makedirs(self.out)
        self.part = os.path.join(self.td.name, "parts", "tools", "widget")
        self.stl = os.path.join(self.part, "stl", "widget.stl")
        self.digest = write_stl(self.stl)
        self.write_spec(self.part)
        self._plate([(self.digest, self.stl)])
        write_verdict(self.part, ["stl/widget.stl"])

    def write_spec(self, part):
        os.makedirs(part, exist_ok=True)
        with open(os.path.join(part, "spec.yaml"), "w") as stream:
            stream.write(qualify_spec("part_id: tools/widget\ndimensions:\n"
                                      "  - {name: w, nominal: 1, tol: 0.1, provenance: measured}\n"))

    def _plate(self, models):
        for name, data in (("plate.3mf", b"3mf"), ("plate_1.gcode", b"gcode"),
                           ("supports.png", b"png")):
            with open(os.path.join(self.out, name), "wb") as stream:
                stream.write(data)
        with open(os.path.join(self.out, "verify_slice.txt"), "w") as stream:
            stream.write("PASS\n")
        with open(os.path.join(self.out, "plate_geom.txt"), "w") as stream:
            for digest, path in models:
                stream.write("%s  %s  %s\n" % (digest[:8], digest, path))
            stream.write("version=test\n")

    def run_handoff(self, **env):
        ensure_future_plate(self.out)
        return subprocess.run([HANDOFF, self.out], cwd=ROOT, text=True, timeout=60,
                              env=dict(os.environ, **env),
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT)

    def assert_refused(self, result, expect):
        self.assertEqual(result.returncode, 14, result.stdout)
        self.assertIn("BREP_VERDICT_RESULT: FAIL", result.stdout)
        self.assertIn(expect, result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.out, "handoff.txt")))

