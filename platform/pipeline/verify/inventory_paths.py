"""Positive, typed model moves in Prusa ASCII G-code; no filenames or header-object counts.

The reported evidence is material-moving XY endpoints in a component's exclusive area across
its height, not a simulated solid or a prediction of successful printing.
"""

import math
import re
from array import array

import numpy as np

MODEL = {
    "Perimeter",
    "External perimeter",
    "Overhang perimeter",
    "Internal infill",
    "Solid infill",
    "Top solid infill",
    "Bridge infill",
    "Internal bridge infill",
    "Gap fill",
    "Thin wall",
    "Ironing",
}
NONMODEL = {
    "Custom",
    "Skirt/Brim",
    "Skirt",
    "Brim",
    "Support material",
    "Support material interface",
    "Wipe tower",
    "Support",
    "Support interface",
    "Purge tower",
    "Travel",
}
PARAM = re.compile(r"([XYZEFIJKR])([-+]?(?:\d+(?:\.\d*)?|\.\d+))")


def deposited(path):
    x = y = z = e = debt = 0.0
    abs_e = abs_axis = True
    kind = ""
    layer = False
    wipe = False
    bed = None
    height = None
    first_cfg = None
    prusa = False
    points = array("d")
    with path.open(encoding="utf-8") as lines:
        for raw in lines:
            if raw.startswith(";"):
                s = raw.strip()
                if s.startswith("; generated by PrusaSlicer "):
                    prusa = True
                elif s.startswith(";TYPE:"):
                    kind = s[6:]
                elif s == ";LAYER_CHANGE":
                    layer = True
                elif s == ";WIPE_START":
                    wipe = True
                elif s == ";WIPE_END":
                    wipe = False
                elif s.startswith("; bed_shape = "):
                    bed = [tuple(map(float, p.split("x"))) for p in s.partition(" = ")[2].split(",")]
                elif s.startswith("; layer_height = "):
                    height = float(s.partition(" = ")[2])
                elif s.startswith("; first_layer_height = "):
                    first_cfg = s.partition(" = ")[2]
                continue
            code = raw.partition(";")[0].strip()
            cmd, _, tail = code.partition(" ")
            if cmd == "M82":
                abs_e = True
            elif cmd == "M83":
                abs_e = False
            elif cmd == "G90":
                abs_axis = True
                abs_e = True
            elif cmd == "G91":
                abs_axis = False
                abs_e = False
            elif cmd == "G92" or cmd in ("G0", "G1", "G2", "G3"):
                args = {k: float(v) for k, v in PARAM.findall(tail)}
                if cmd == "G92":
                    if any(k in args for k in "XYZ"):
                        raise ValueError("shifted G92 XYZ work coordinates not supported")
                    e = args.get("E", e)
                    continue
                nx = args.get("X", x) if abs_axis else x + args.get("X", 0.0)
                ny = args.get("Y", y) if abs_axis else y + args.get("Y", 0.0)
                nz = args.get("Z", z) if abs_axis else z + args.get("Z", 0.0)
                de = (args["E"] - e if abs_e else args["E"]) if "E" in args else 0.0
                e += de
                deposit = de - debt
                debt = max(0.0, debt - de)
                if (
                    layer
                    and not wipe
                    and deposit > 1e-8
                    and (nx != x or ny != y or (cmd in ("G2", "G3") and any(k in args for k in "IJR")))
                ):
                    if kind in MODEL:
                        points.extend((x, y, nx, ny, nz))
                    elif kind not in NONMODEL:
                        raise ValueError("unknown deposition role: " + repr(kind))
                x, y, z = nx, ny, nz
            elif cmd in (
                "G5",
                "G10",
                "G11",
                "G20",
                "G52",
                "G53",
                "G54",
                "G55",
                "G56",
                "G57",
                "G58",
                "G59",
                "G68",
                "G69",
                "M200",
            ) or (layer and cmd == "G28"):
                raise ValueError("unsupported coordinate/extrusion mode: " + cmd)
    if not prusa or not layer or not height or not (0 < height <= 2) or not len(points):
        raise ValueError("no supported layered Prusa model-extrusion evidence")
    first = (
        height
        if first_cfg is None
        else float(first_cfg[:-1]) * height / 100
        if first_cfg.endswith("%")
        else float(first_cfg)
    )
    if not 0 < first <= 2:
        raise ValueError("invalid first_layer_height")
    return np.frombuffer(points).reshape(-1, 5), bed, height, first


def projected_cells(mesh):
    # 1 mm cells. In each horizontal strip intersect the three edges at both boundaries,
    # include interior vertices, then cover the inclusive X interval. Allow 0.12 mm for
    # external line-centre offsets and decimals. Extra covered cells can only lose exclusivity.
    pad = 0.12
    xy = mesh[:, :, :2]
    low = np.floor(xy.min(axis=(0, 1)) - pad).astype(int)
    high = np.floor(xy.max(axis=(0, 1)) + pad).astype(int)
    x0, y0 = map(int, low)
    w, h = map(int, high - low + 1)
    if w * h > 4_000_000:
        raise ValueError("unsupported projected envelope")
    cover = np.zeros((h, w), bool)
    for tri in xy.tolist():
        edges = tuple(zip(tri, tri[1:] + tri[:1]))
        ys = [p[1] for p in tri]
        for row in range(math.floor(min(ys) - pad), math.floor(max(ys) + pad) + 1):
            a = row - pad
            b = row + 1 + pad
            xs = [x for x, y in tri if a <= y <= b]
            for (x, y), (X, Y) in edges:
                if Y != y:
                    for cut in (a, b):
                        if min(y, Y) < cut < max(y, Y):
                            xs.append(x + (X - x) * (cut - y) / (Y - y))
            if xs:
                cover[row - y0, math.floor(min(xs) - pad) - x0 : math.floor(max(xs) + pad) - x0 + 1] = True
    return cover, x0, y0


def witnesses(meshes, gcode, registration):
    moves, bed, nominal, first = deposited(gcode)
    lo = np.array([m.min(axis=(0, 1)) for m in meshes])
    hi = np.array([m.max(axis=(0, 1)) for m in meshes])
    shift = np.zeros(3)
    if registration == "center-bed":
        bed = np.array(bed, dtype=float)
        if bed.ndim != 2 or bed.shape[1] != 2 or len(bed) < 3 or not np.isfinite(bed).all():
            raise ValueError("missing/invalid G-code bed_shape")
        shift[:2] = (bed.min(0) + bed.max(0) - lo.min(0)[:2] - hi.max(0)[:2]) / 2
        shift[2] = -lo.min(0)[2]
    # Cover each (possibly concave) XY projection conservatively, without filling holes or a
    # runner's entire bounding box. A move qualifies only when both endpoints belong to the
    # same body; an overlap is never credited to both. No path fitting or per-part recentering.
    n = len(moves)
    hits = np.zeros(n, dtype=np.int32)
    owner = np.full(n, -1, dtype=np.int32)
    tiles = np.floor(moves[:, :4] - np.tile(shift[:2], 2)).astype(np.int64)
    for i, m in enumerate(meshes):
        cover, x0, y0 = projected_cells(m)
        b = lo[i] + shift
        t = hi[i] + shift
        x, y, X, Y = (tiles - np.array([x0, y0, x0, y0])).T
        h, w = cover.shape
        mask = (
            (moves[:, 4] >= b[2] - 0.001)
            & (moves[:, 4] <= t[2] + nominal + 0.001)
            & (x >= 0)
            & (X >= 0)
            & (y >= 0)
            & (Y >= 0)
            & (x < w)
            & (X < w)
            & (y < h)
            & (Y < h)
        )
        idx = np.flatnonzero(mask)
        idx = idx[cover[y[idx], x[idx]] & cover[Y[idx], X[idx]]]
        hits[idx] += 1
        owner[idx] = i
    rows = []
    z = moves[:, 4]
    for i in range(len(meshes)):
        zz = np.unique(z[(hits == 1) & (owner == i)])
        bottom = lo[i, 2] + shift[2]
        top = hi[i, 2] + shift[2]
        # In this adapter physical pieces start on the bed; unsupported suspended or adaptive
        # layers must not become a guessed count. Allow at most half a nominal layer for top rounding.
        ok = bool(
            len(zz)
            and abs(bottom) < 0.001
            and abs(zz[0] - first) < 0.003
            and abs(zz[-1] - max(first, top)) <= nominal / 2 + 0.002
            and (len(zz) == 1 or np.diff(zz).max() <= nominal + 0.003)
        )
        rows.append(
            {
                "exclusive_moves": int(np.sum((hits == 1) & (owner == i))),
                "layers": len(zz),
                "z_min": round(float(zz[0]), 4) if len(zz) else None,
                "z_max": round(float(zz[-1]), 4) if len(zz) else None,
                "through_height": ok,
            }
        )
    return rows, {
        "xy_shift_mm": shift[:2].round(5).tolist(),
        "unassigned_model_moves": int(np.sum(hits == 0)),
        "ambiguous_model_moves": int(np.sum(hits > 1)),
    }
