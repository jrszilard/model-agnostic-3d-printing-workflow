class MeasurementDebtAtTheHandoff(unittest.TestCase):
    """The half of the debt state that has to keep working when nobody is watching.

    Letting a prototype cross declared debt is the point; refusing it on a release is the reason
    the state is safe to have. Both are asserted here, plus the default for a plate that cannot
    say what it is — because the deadlock this state broke was itself two gates independently
    agreeing on something nobody had tested end to end.
    """

    def setUp(self):
        self.h = HandoffProvenanceTests("run_handoff")
        self.h.setUp()
        self.addCleanup(self.h.td.cleanup)
        due = (datetime.date.today() + datetime.timedelta(days=365)).isoformat()
        body = ("part_id: test/part\ndimensions:\n"
                "  - {name: bore, nominal: 10, tol: 0.1, provenance: pending-measurement,\n"
                "     fit_critical: true, closes_with: the prototype on this plate,\n"
                "     next_review: %s}\n"
                "probes:\n"
                "  - {id: bore-empty, expect: outside, region: {shape: box}}\n" % due)
        with open(os.path.join(self.h.part, "spec.yaml"), "w") as stream:
            stream.write(qualify_spec(body))
        write_verdict(self.h.part, ["part.stl"], verdict="DEBT")

    def set_kind(self, kind):
        if kind is None:
            return
        with open(os.path.join(self.h.out, "preparation.json"), "w") as stream:
            json.dump({"schema": 1, "kind": kind}, stream)

    def test_prototype_may_cross_declared_debt(self):
        self.set_kind("prototype")
        result = self.h.run_handoff()
        self.assertEqual(result.returncode, 0, result.stdout)
        with open(os.path.join(self.h.out, "qualification_manifest.json")) as stream:
            manifest = json.load(stream)
        # The manifest records what was actually approved, not a constant.
        self.assertEqual(manifest["parts"][0]["verify"]["verdict"], "DEBT")

    def test_release_may_not_carry_an_unproven_fit_critical_nominal(self):
        self.set_kind("release")
        result = self.h.run_handoff()
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertIn("release", result.stdout.lower())
        self.assertFalse(os.path.exists(os.path.join(self.h.out, "handoff.txt")))

    def test_a_plate_that_cannot_say_what_it_is_reads_as_a_release(self):
        self.set_kind(None)
        result = self.h.run_handoff()
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.h.out, "handoff.txt")))


class HandoffPartDerivationTests(unittest.TestCase):
    """The part dir used to be an optional argument, so omitting it skipped every truth gate and
    still wrote handoff.txt. These pin the derived behaviour and the deliberate limits on it."""

    def _plate(self, stl_path):
        """Build a complete plate whose single model is `stl_path`."""
        os.makedirs(os.path.dirname(stl_path), exist_ok=True)
        with open(stl_path, "w") as stream:
            stream.write(STL)
        subprocess.run(["python3", C14N, stl_path], check=True, stdout=subprocess.PIPE)
        with open(stl_path, "rb") as stream:
            digest = hashlib.sha256(stream.read()).hexdigest()
        for name, data in (("plate.3mf", b"3mf"), ("plate_1.gcode", b"gcode"),
                           ("supports.png", b"png")):
            with open(os.path.join(self.out, name), "wb") as stream:
                stream.write(data)
        with open(os.path.join(self.out, "verify_slice.txt"), "w") as stream:
            stream.write("PASS\n")
        with open(os.path.join(self.out, "plate_geom.txt"), "w") as stream:
            stream.write("%s  %s  %s\nversion=test\n" % (digest[:8], digest, stl_path))
        return digest[:8]

    def record_verdict(self):
        write_verdict(self.part, [os.path.relpath(self.stl, self.part)])

    def setUp(self):
        self.td = tempfile.TemporaryDirectory(); self.addCleanup(self.td.cleanup)
        self.out = os.path.join(self.td.name, "build"); os.makedirs(self.out)
        # A realistic authored-part path: the refusal is scoped to models under parts/.
        self.part = os.path.join(self.td.name, "parts", "tools", "widget")
        self.stl = os.path.join(self.part, "stl", "widget.stl")

    def run_handoff(self, *args, **env):
        ensure_future_plate(self.out)
        environ = dict(os.environ, UNSTAMPED_OK="1", **env)   # previews are a separate gate
        return subprocess.run([HANDOFF, self.out, *args], cwd=ROOT, text=True, env=environ,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT)

    def write_spec(self, body):
        os.makedirs(self.part, exist_ok=True)
        with open(os.path.join(self.part, "spec.yaml"), "w") as stream:
            stream.write(qualify_spec(body))

    def test_spec_truth_runs_without_the_part_argument(self):
        """The whole point: no second argument, and the gate still runs."""
        self._plate(self.stl)
        self.write_spec("part_id: t/w\ndimensions:\n"
                        "  - {name: bore, nominal: 10, tol: 0.1, provenance: measured,"
                        " fit_critical: true}\n"
                        "probes:\n  - {id: bore-empty, expect: outside, region: {shape: box}}\n")
        self.record_verdict()
        result = self.run_handoff()
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn("SPEC TRUTH", result.stdout)
        self.assertIn("PROVENANCE_RESULT: PASS", result.stdout)
        with open(os.path.join(self.out, "handoff.txt")) as stream:
            self.assertIn("spec_part=", stream.read())

    def test_ignored_legacy_fallback_is_refused_when_selected_for_a_new_plate(self):
        """No archive rewrite; selecting old draft geometry for a plate is the adoption edge."""
        self.stl = os.path.join(self.part, "stl", "widget--draft-old.stl")
        self._plate(self.stl)
        with open(os.path.join(self.td.name, ".gitignore"), "w") as stream:
            stream.write("**/*--draft-*.stl\n")
        self.write_spec("part_id: t/w\ndimensions: []\n")
        self.record_verdict()
        result = self.run_handoff()
        self.assertEqual(result.returncode, 12, result.stdout)
        self.assertIn("SPEC_PRIMARY_RESULT: FAIL", result.stdout)
        self.assertIn("next plate boundary", result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.out, "handoff.txt")))

    def test_part_under_parts_with_no_spec_refuses_13(self):
        """The wiper-arm-adaptor case: eleven plates, no spec.yaml, every gate silently skipped."""
        self._plate(self.stl)
        result = self.run_handoff()
        self.assertEqual(result.returncode, 13, result.stdout)
        self.assertIn("has no spec.yaml", result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.out, "handoff.txt")))

    def test_no_spec_ok_bypasses_13_only_and_still_meets_the_verdict_gate(self):
        """The usage line says NO_SPEC_OK "bypasses 13 only". Measured 2026-09-04 it also bypassed
        14: a part under parts/ with no spec.yaml has no part directory, so the verdict loop ran
        over an empty list and reported PASS. A part with neither a spec nor a B-rep verdict is
        exactly what A1 exists to stop."""
        self._plate(self.stl)
        result = self.run_handoff(NO_SPEC_OK="1")
        self.assertEqual(result.returncode, 14, result.stdout)
        self.assertIn("no part directory to hold", result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.out, "handoff.txt")))

    def test_a_spec_and_a_verdict_together_reach_a_complete_handoff(self):
        """The way past both refusals, so the pair above is not merely "everything fails"."""
        self._plate(self.stl)
        self.write_spec("part_id: t/w\ndimensions:\n"
                        "  - {name: bore, nominal: 10, tol: 0.1, provenance: measured}\n")
        self.record_verdict()
        result = self.run_handoff()
        self.assertEqual(result.returncode, 0, result.stdout)
        with open(os.path.join(self.out, "handoff.txt")) as stream:
            self.assertIn("brep_verdict=PASS", stream.read())

    def test_build_local_model_is_unchecked_not_refused(self):
        """Support blockers and arrangement 3mfs live in build/ and have no part dir by design.
        Refusing them would mean typing the bypass on every run of a validation loop."""
        self._plate(os.path.join(self.out, "support-blocker.stl"))
        result = self.run_handoff()
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn("[unchecked]", result.stdout)

    def test_fit_bearing_spec_without_provenance_blocks(self):
        """Item 07's rule, biting where it matters: a declared fit plus an unsourced number."""
        self._plate(self.stl)
        self.write_spec("part_id: t/w\ndimensions:\n"
                        "  - {name: bore, nominal: 10, tol: 0.1}\n"
                        "fits:\n  - {name: slides_on, type: slip, mates_with: a shaft}\n")
        result = self.run_handoff()
        self.assertEqual(result.returncode, 12, result.stdout)
        self.assertIn("every dimension must record provenance", result.stdout)


