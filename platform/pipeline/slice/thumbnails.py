"""thumbnails.py — embed preview images into OrcaSlicer gcode.

OrcaSlicer's CLI runs headless with no GL context, so it silently skips thumbnail rendering even
when the machine preset asks for them (`thumbnails: ['96x96','300x300']` on the K1C). Fluidd and
the printer's LCD then show a blank tile. This module re-adds the blocks in the exact format the
GUI emits — pinned byte-for-byte by testdata/gui_sliced_header.gcode.

Only the sizes the preset requests need embedding: Moonraker derives the extra sizes its UI wants
(48x48, 195x195) from the largest embedded image.

Format note: the number on the `begin` line is the BASE64 CHARACTER COUNT, not the decoded byte
count. Get that wrong and Moonraker reads a truncated image.
"""
import base64
import json
import os
import re
import subprocess
import sys
import tempfile

HEADER_END = "; HEADER_BLOCK_END"
PRUSA_GENERATOR = "; generated by PrusaSlicer"
WRAP = 78  # base64 chars per line; "; " prefix brings the line to 80
CAMERA = "0,0,0,55,0,25,0"  # same iso view as preview/render.sh
DEFAULT_SIZES = ["96x96", "300x300"]
# The Core One preset asks for 16x16/QOI, 313x173/QOI, 480x240/QOI, 380x285/PNG. Only the PNG
# one is emitted here: the QOI-tagged sizes must actually be QOI-encoded, and PNG bytes under a
# thumbnail_QOI tag would be read as a corrupt image rather than ignored.
PRUSA_DEFAULT_SIZES = ["380x285"]

_BEGIN = re.compile(r"^; thumbnail begin (\d+)x(\d+) (\d+)\s*$")


def render_png(stls, width, height):
    """Render the plate's STLs to a PNG of exactly width x height, via OpenSCAD offscreen."""
    openscad = os.environ.get("OPENSCAD", "openscad")
    with tempfile.TemporaryDirectory() as d:
        scad, png = os.path.join(d, "t.scad"), os.path.join(d, "t.png")
        with open(scad, "w") as f:
            for s in stls:
                f.write('import("%s");\n' % os.path.abspath(s))
        subprocess.run([openscad, "-o", png, f"--imgsize={width},{height}",
                        "--viewall", "--autocenter", f"--camera={CAMERA}",
                        "--colorscheme=Tomorrow", scad],
                       check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        with open(png, "rb") as f:
            return f.read()


def parse_sizes(values):
    """The machine preset's `thumbnails` field: ['96x96', '300x300'] -> [(96, 96), (300, 300)]"""
    out = []
    for v in values:
        m = re.fullmatch(r"(\d+)x(\d+)", str(v).strip().lower())
        if not m:
            raise ValueError(f"malformed thumbnail size: {v!r} (expected e.g. '96x96')")
        out.append((int(m.group(1)), int(m.group(2))))
    return out


def find_thumbnails(gcode):
    """Read back every embedded thumbnail as (width, height, png_bytes)."""
    out, lines = [], gcode.split("\n")
    for i, line in enumerate(lines):
        m = _BEGIN.match(line)
        if not m:
            continue
        payload = []
        for nxt in lines[i + 1:]:
            if nxt.startswith("; thumbnail end"):
                break
            payload.append(nxt[2:] if nxt.startswith("; ") else nxt.lstrip("; "))
        out.append((int(m.group(1)), int(m.group(2)), base64.b64decode("".join(payload))))
    return out


def strip_thumbnails(gcode):
    """Remove every THUMBNAIL_BLOCK, plus the blank line that separates it from what follows."""
    lines, out, i = gcode.split("\n"), [], 0
    while i < len(lines):
        if lines[i] == "; THUMBNAIL_BLOCK_START":
            while i < len(lines) and lines[i] != "; THUMBNAIL_BLOCK_END":
                i += 1
            i += 1                                    # past THUMBNAIL_BLOCK_END
            if i < len(lines) and lines[i] == "":     # and its trailing blank
                i += 1
            continue
        out.append(lines[i])
        i += 1
    return "\n".join(out)


def _block(width, height, png):
    payload = base64.b64encode(png).decode("ascii")
    lines = ["; THUMBNAIL_BLOCK_START", "", ";",
             f"; thumbnail begin {width}x{height} {len(payload)}"]
    lines += [f"; {payload[i:i + WRAP]}" for i in range(0, len(payload), WRAP)]
    lines += ["; thumbnail end", "; THUMBNAIL_BLOCK_END"]
    return "\n".join(lines)


def _prusa_block(width, height, png):
    """PrusaSlicer's own thumbnail shape: no THUMBNAIL_BLOCK wrapper, bare `;` fences."""
    payload = base64.b64encode(png).decode("ascii")
    lines = [";", f"; thumbnail begin {width}x{height} {len(payload)}"]
    lines += [f"; {payload[i:i + WRAP]}" for i in range(0, len(payload), WRAP)]
    lines += ["; thumbnail end", ";"]
    return "\n".join(lines)


def strip_prusa_thumbnails(gcode):
    """Remove bare `; thumbnail begin`..`end` runs (PrusaSlicer flavour) and their `;` fences."""
    lines, out, i = gcode.split("\n"), [], 0
    while i < len(lines):
        if _BEGIN.match(lines[i]):
            if out and out[-1] == ";":
                out.pop()
            while i < len(lines) and not lines[i].startswith("; thumbnail end"):
                i += 1
            i += 1                                    # past the end line
            if i < len(lines) and lines[i] == ";":    # and its closing fence
                i += 1
            continue
        out.append(lines[i])
        i += 1
    return "\n".join(out)


def inject_thumbnails(gcode, thumbs):
    """Insert thumbnails after the header. Idempotent: replaces any existing ones.

    Two flavours: OrcaSlicer anchors on `; HEADER_BLOCK_END` and wraps each image in a
    THUMBNAIL_BLOCK; PrusaSlicer has neither, and takes its thumbnails immediately after the
    generator line. Emitting the Orca shape into Prusa gcode gets it silently ignored.
    """
    if not thumbs:
        return gcode
    if HEADER_END in gcode:
        gcode = strip_thumbnails(gcode)
        at = gcode.index(HEADER_END) + len(HEADER_END)
        blocks = "\n\n".join(_block(w, h, png) for w, h, png in thumbs)
        return f"{gcode[:at]}\n\n{blocks}{gcode[at:]}"
    if PRUSA_GENERATOR in gcode:
        gcode = strip_prusa_thumbnails(gcode)
        at = gcode.index(PRUSA_GENERATOR)
        at = gcode.index("\n", at)                    # end of the generator line
        blocks = "\n".join(_prusa_block(w, h, png) for w, h, png in thumbs)
        return f"{gcode[:at]}\n{blocks}{gcode[at:]}"
    raise ValueError(f"cannot place thumbnails: no {HEADER_END} or {PRUSA_GENERATOR} in gcode")


def _sizes_from_machine(path):
    try:
        with open(path) as f:
            return json.load(f).get("thumbnails") or DEFAULT_SIZES
    except (OSError, ValueError):
        return DEFAULT_SIZES


def main(argv):
    gcode_path = machine = None
    sizes, stls = None, []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--gcode":
            i += 1; gcode_path = argv[i]
        elif a == "--machine":
            i += 1; machine = argv[i]
        elif a == "--sizes":
            i += 1; sizes = argv[i].split(",")
        else:
            stls.append(a)
        i += 1
    if not gcode_path or not stls:
        print("usage: thumbnails.py --gcode <f.gcode> [--machine <m.json>] "
              "[--sizes 96x96,300x300] <stl>...", file=sys.stderr)
        return 2

    with open(gcode_path) as f:
        gcode = f.read()
    if sizes is None:
        if machine:
            sizes = _sizes_from_machine(machine)
        else:
            sizes = PRUSA_DEFAULT_SIZES if PRUSA_GENERATOR in gcode else DEFAULT_SIZES

    thumbs = [(w, h, render_png(stls, w, h)) for w, h in parse_sizes(sizes)]
    with open(gcode_path, "w") as f:
        f.write(inject_thumbnails(gcode, thumbs))
    print("thumbnails: embedded %s into %s" %
          (", ".join(f"{w}x{h}" for w, h, _ in thumbs), os.path.basename(gcode_path)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
