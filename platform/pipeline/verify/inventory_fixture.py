"""Small synthetic boxes for offline unit tests; never a real printable job or an approval."""

import hashlib
import json
import struct
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile

NS = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"
FACES = (
    (0, 2, 1),
    (0, 3, 2),
    (4, 5, 6),
    (4, 6, 7),
    (0, 1, 5),
    (0, 5, 4),
    (1, 2, 6),
    (1, 6, 5),
    (2, 3, 7),
    (2, 7, 6),
    (3, 0, 4),
    (3, 4, 7),
)
SIZES = {"clip": (4, 4, 0.6), "foot": (8, 6, 0.6)}


def box(size):
    x, y, z = size
    return [(0, 0, 0), (x, 0, 0), (x, y, 0), (0, y, 0), (0, 0, z), (x, 0, z), (x, y, z), (0, y, z)]


def mesh_bytes(size):
    v = box(size)
    return (
        bytes(80)
        + struct.pack("<I", len(FACES))
        + b"".join(struct.pack("<12fH", 0, 0, 0, *v[a], *v[b], *v[c], 0) for a, b, c in FACES)
    )


def project(p, instances):
    root = ET.Element("model", xmlns=NS, unit="millimeter")
    res = ET.SubElement(root, "resources")
    build = ET.SubElement(root, "build")
    for idx, (k, size) in enumerate(SIZES.items(), 1):
        # Object names are deliberately not the source of the part IDs.
        o = ET.SubElement(res, "object", id=str(idx), type="model", name="misleading filename")
        m = ET.SubElement(o, "mesh")
        v = ET.SubElement(m, "vertices")
        f = ET.SubElement(m, "triangles")
        for row in box(size):
            ET.SubElement(v, "vertex", dict(zip("xyz", map(str, row))))
        for row in FACES:
            ET.SubElement(f, "triangle", dict(zip(("v1", "v2", "v3"), map(str, row))))
    for k, x, y, printable in instances:
        ET.SubElement(
            build,
            "item",
            objectid=str(list(SIZES).index(k) + 1),
            transform=f"1 0 0 0 1 0 0 0 1 {x} {y} 0",
            printable=str(int(printable)),
        )
    with ZipFile(p / "plate.3mf", "w") as z:
        z.writestr("3D/3dmodel.model", ET.tostring(root))


def package(p, wants=None, instances=None, paths=None):
    """Synthetic *independent* request, reference meshes, project and final model moves."""
    p = Path(p)
    p.mkdir(exist_ok=True)
    wants = {"clip": 1} if wants is None else wants
    instances = [("clip", 10, 10, True)] if instances is None else instances
    paths = [(x, y, "Perimeter") for _, x, y, active in instances if active] if paths is None else paths
    store = p / "inventory-models"
    store.mkdir(exist_ok=True)
    refs = {}
    for k, size in SIZES.items():
        data = mesh_bytes(size)
        h = hashlib.sha256(data).hexdigest()
        (store / (h + ".stl")).write_bytes(data)
        refs[k] = h
    (p / "inventory-catalog.json").write_text(
        json.dumps({"schema": 1, "placement": "as-saved", "models": refs})
    )
    (p / "plate-request.json").write_text(json.dumps({"schema": 1, "requested": wants}))
    project(p, instances)
    lines = [
        "; generated by PrusaSlicer test",
        "; filament used [g] = 1.0",
        "; estimated printing time (normal mode) = 1m",
        "G21",
        "G90",
        "M83",
    ]
    for z in (0.2, 0.4, 0.6):
        lines += [";LAYER_CHANGE", f";Z:{z}", f"G1 Z{z}"]
        for x, y, role in paths:
            lines += [";TYPE:" + role, f"G0 X{x + 1} Y{y + 1}", f"G1 X{x + 2} Y{y + 1} E0.03"]
    lines += [
        "; prusaslicer_config = begin",
        "; bed_shape = 0x0,250x0,250x220,0x220",
        "; layer_height = 0.2",
        "; prusaslicer_config = end",
    ]
    (p / "plate_1.gcode").write_text("\n".join(lines) + "\n")
    restamp(p)


def restamp(p):
    sha = lambda n: hashlib.sha256((p / n).read_bytes()).hexdigest()
    (p / "slice_meta.json").write_text(
        json.dumps(
            {
                "schema": 2,
                "artifacts": {"project_3mf_sha256": sha("plate.3mf"), "gcode_sha256": sha("plate_1.gcode")},
            }
        )
    )
