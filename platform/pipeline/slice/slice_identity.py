#!/usr/bin/env python3
"""Record and verify the exact slicer/profile inputs behind a plate.

`plate_geom.txt` binds models to the slice and `gcode_manifest.json` binds post-processing to the
final G-code.  Neither identifies the selected machine/process/filament profiles or the effective
configuration PrusaSlicer embedded in that G-code.  This file closes that gap without claiming that
the profile is suitable: it records identity only, then fails closed if those bytes move.

Usage:
  slice_identity.py write --meta M --gcode G --project P --overrides O \
      --slicer EXE --machine NAME --process NAME --filament NAME \
      --rotate-x N --rotate-y N --rotate-z N [--support-requested] \
      [--spec PATH] [--override KEY=VALUE ...] [--post-hook PATH ...]
  slice_identity.py check --meta M --gcode G --project P --overrides O
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import re
import shutil
import sys
from pathlib import Path

SCHEMA = 2
_SHA256 = re.compile(r"^[0-9a-f]{64}$")


def sha256_file(path: str | os.PathLike[str]) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def embedded_config_bytes(gcode: str | os.PathLike[str]) -> bytes | None:
    """Return PrusaSlicer's complete embedded config block, markers included."""
    with open(gcode, "rb") as stream:
        lines = stream.readlines()
    start = next((i for i, line in enumerate(lines)
                  if line.strip() == b"; prusaslicer_config = begin"), None)
    if start is None:
        return None
    end = next((i for i in range(start + 1, len(lines))
                if lines[i].strip() == b"; prusaslicer_config = end"), None)
    if end is None:
        return None
    return b"".join(lines[start:end + 1])


def generator_line(gcode: str | os.PathLike[str]) -> str | None:
    with open(gcode, "r", encoding="utf-8", errors="replace") as stream:
        for _ in range(50):
            line = stream.readline()
            if not line:
                break
            match = re.match(r";\s*generated by\s+(.+?)\s*$", line, re.IGNORECASE)
            if match:
                return match.group(1)
    return None


def _real_executable(value: str) -> str:
    found = shutil.which(value)
    return os.path.realpath(found or value)


def build_metadata(*, gcode: str, project: str, overrides_path: str, slicer: str,
                   machine: str, process: str, filament: str, rotation: dict,
                   support_requested: bool, spec: str | None, overrides: list[str],
                   post_hooks: list[str], colour_regions: list[str] = ()) -> dict:
    # G-code and its effective overrides are the shipped-process identity. The 3MF remains a
    # review convenience: slice.sh has always allowed its parallel export to fail while keeping a
    # valid G-code, and handoff.sh separately requires it before presentation.
    for path, label in ((gcode, "G-code"), (overrides_path, "override configuration")):
        if not os.path.isfile(path):
            raise ValueError(f"missing {label}: {path}")
    config = embedded_config_bytes(gcode)
    if config is None:
        raise ValueError("final G-code has no complete PrusaSlicer embedded-config block")
    generated_by = generator_line(gcode)
    if not generated_by:
        raise ValueError("final G-code does not identify its generator")
    hooks = []
    for path in post_hooks:
        if not os.path.isfile(path):
            raise ValueError(f"missing post hook: {path}")
        hooks.append({"path": os.path.realpath(path), "sha256": sha256_file(path)})
    # Colour regions (slice.sh --colour <stl>=<n>) decide which filament prints where, so they are
    # shipped-process input like a hook: bound by bytes, re-hashed by every check.
    regions = []
    for item in colour_regions:
        path, _, filament = item.rpartition("=")
        if not os.path.isfile(path) or not filament.isdigit():
            raise ValueError(f"bad colour region: {item}")
        regions.append({"path": os.path.realpath(path), "filament": int(filament),
                        "sha256": sha256_file(path)})
    return {
        "schema": SCHEMA,
        "slicer": {"executable": _real_executable(slicer),
                   "reported_by_gcode": generated_by},
        "profiles": {"machine": machine, "process": process, "filament": filament},
        "rotation": {axis: float(rotation[axis]) for axis in ("x", "y", "z")},
        "support_requested": bool(support_requested),
        "spec": os.path.realpath(spec) if spec else None,
        "overrides": list(overrides),
        "post_hooks": hooks,
        "colour_regions": regions,
        "artifacts": {
            "gcode_sha256": sha256_file(gcode),
            "project_3mf_sha256": sha256_file(project) if os.path.isfile(project) else None,
            "overrides_sha256": sha256_file(overrides_path),
            "effective_config_sha256": hashlib.sha256(config).hexdigest(),
        },
    }


def write_metadata(path: str, **kwargs) -> dict:
    data = build_metadata(**kwargs)
    os.makedirs(os.path.dirname(os.path.realpath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as stream:
        json.dump(data, stream, indent=2, sort_keys=True)
        stream.write("\n")
    os.replace(tmp, path)
    return data


def evaluate(data: object, *, gcode: str, project: str, overrides_path: str) -> dict:
    errors: list[str] = []
    if not isinstance(data, dict):
        return {"passed": False, "errors": ["metadata is not a JSON object"]}
    if data.get("schema") != SCHEMA:
        errors.append(f"schema must be {SCHEMA}, got {data.get('schema')!r}")

    slicer = data.get("slicer")
    if not isinstance(slicer, dict):
        errors.append("slicer must be a mapping")
    else:
        for key in ("executable", "reported_by_gcode"):
            if not isinstance(slicer.get(key), str) or not slicer[key].strip():
                errors.append(f"slicer.{key} is missing")

    profiles = data.get("profiles")
    if not isinstance(profiles, dict):
        errors.append("profiles must be a mapping")
    else:
        for key in ("machine", "process", "filament"):
            if not isinstance(profiles.get(key), str) or not profiles[key].strip():
                errors.append(f"profiles.{key} is missing")

    rotation = data.get("rotation")
    if not isinstance(rotation, dict):
        errors.append("rotation must be a mapping")
    else:
        for axis in ("x", "y", "z"):
            value = rotation.get(axis)
            if (not isinstance(value, (int, float)) or isinstance(value, bool)
                    or not math.isfinite(value)):
                errors.append(f"rotation.{axis} must be finite")

    if not isinstance(data.get("support_requested"), bool):
        errors.append("support_requested must be boolean")
    if not isinstance(data.get("overrides"), list) \
            or not all(isinstance(item, str) for item in data.get("overrides", [])):
        errors.append("overrides must be a list of strings")

    hooks = data.get("post_hooks")
    if not isinstance(hooks, list):
        errors.append("post_hooks must be a list")
    else:
        for index, hook in enumerate(hooks):
            if not isinstance(hook, dict):
                errors.append(f"post_hooks[{index}] must be a mapping")
                continue
            path, recorded = hook.get("path"), hook.get("sha256")
            if not isinstance(path, str) or not path:
                errors.append(f"post_hooks[{index}].path is missing")
            elif not os.path.isfile(path):
                errors.append(f"post hook is no longer readable: {path}")
            elif recorded != sha256_file(path):
                errors.append(f"post hook changed after slicing: {path}")
            if not isinstance(recorded, str) or not _SHA256.fullmatch(recorded):
                errors.append(f"post_hooks[{index}].sha256 is invalid")

    regions = data.get("colour_regions", [])       # absent in metadata written before 2026-10-06
    if not isinstance(regions, list):
        errors.append("colour_regions must be a list")
    else:
        for index, region in enumerate(regions):
            if not isinstance(region, dict):
                errors.append(f"colour_regions[{index}] must be a mapping")
                continue
            path, recorded = region.get("path"), region.get("sha256")
            if not isinstance(path, str) or not path:
                errors.append(f"colour_regions[{index}].path is missing")
            elif not os.path.isfile(path):
                errors.append(f"colour region is no longer readable: {path}")
            elif recorded != sha256_file(path):
                errors.append(f"colour region changed after slicing: {path}")
            if not isinstance(region.get("filament"), int) or region["filament"] < 2:
                errors.append(f"colour_regions[{index}].filament must be 2 or more")

    artifacts = data.get("artifacts")
    if not isinstance(artifacts, dict):
        errors.append("artifacts must be a mapping")
        artifacts = {}
    expected_paths = {
        "gcode_sha256": gcode,
        "overrides_sha256": overrides_path,
    }
    for key, path in expected_paths.items():
        recorded = artifacts.get(key)
        if not isinstance(recorded, str) or not _SHA256.fullmatch(recorded):
            errors.append(f"artifacts.{key} is invalid")
        elif not os.path.isfile(path):
            errors.append(f"artifact is missing: {path}")
        elif recorded != sha256_file(path):
            errors.append(f"artifact changed after slice metadata was written: {path}")

    project_sha = artifacts.get("project_3mf_sha256")
    if project_sha is not None and (not isinstance(project_sha, str)
                                    or not _SHA256.fullmatch(project_sha)):
        errors.append("artifacts.project_3mf_sha256 is invalid")
    elif project_sha is not None:
        if not os.path.isfile(project):
            errors.append(f"recorded 3MF project is missing: {project}")
        elif project_sha != sha256_file(project):
            errors.append(f"artifact changed after slice metadata was written: {project}")
    elif os.path.isfile(project):
        errors.append("3MF project exists but slice metadata does not bind its bytes")

    recorded_config = artifacts.get("effective_config_sha256")
    if not isinstance(recorded_config, str) or not _SHA256.fullmatch(recorded_config):
        errors.append("artifacts.effective_config_sha256 is invalid")
    elif os.path.isfile(gcode):
        config = embedded_config_bytes(gcode)
        if config is None:
            errors.append("final G-code has no complete PrusaSlicer embedded-config block")
        elif hashlib.sha256(config).hexdigest() != recorded_config:
            errors.append("effective embedded slicer configuration changed")
        reported = generator_line(gcode)
        if reported and isinstance(slicer, dict) \
                and slicer.get("reported_by_gcode") != reported:
            errors.append("G-code generator identity changed")

    return {"passed": not errors, "errors": errors}


def load_and_evaluate(meta: str, **paths) -> dict:
    try:
        with open(meta, encoding="utf-8") as stream:
            data = json.load(stream)
    except (OSError, json.JSONDecodeError) as exc:
        return {"passed": False, "errors": [f"cannot read slice metadata: {exc}"]}
    return evaluate(data, **paths)


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    write = sub.add_parser("write")
    check = sub.add_parser("check")
    for command in (write, check):
        command.add_argument("--meta", required=True)
        command.add_argument("--gcode", required=True)
        command.add_argument("--project", required=True)
        command.add_argument("--overrides", dest="overrides_path", required=True)
    write.add_argument("--slicer", required=True)
    write.add_argument("--machine", required=True)
    write.add_argument("--process", required=True)
    write.add_argument("--filament", required=True)
    write.add_argument("--rotate-x", type=float, default=0.0)
    write.add_argument("--rotate-y", type=float, default=0.0)
    write.add_argument("--rotate-z", type=float, default=0.0)
    write.add_argument("--support-requested", action="store_true")
    write.add_argument("--spec")
    write.add_argument("--override", action="append", default=[])
    write.add_argument("--post-hook", action="append", default=[])
    write.add_argument("--colour-region", action="append", default=[])
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    if args.command == "write":
        try:
            write_metadata(
                args.meta, gcode=args.gcode, project=args.project,
                overrides_path=args.overrides_path, slicer=args.slicer,
                machine=args.machine, process=args.process, filament=args.filament,
                rotation={"x": args.rotate_x, "y": args.rotate_y, "z": args.rotate_z},
                support_requested=args.support_requested, spec=args.spec,
                overrides=args.override, post_hooks=args.post_hook,
                colour_regions=args.colour_region)
        except (OSError, ValueError) as exc:
            print(f"SLICE_IDENTITY_RESULT: FAIL — {exc}", file=sys.stderr)
            return 1
        print(f"slice identity -> {args.meta}")
        print("SLICE_IDENTITY_RESULT: PASS")
        return 0

    result = load_and_evaluate(args.meta, gcode=args.gcode, project=args.project,
                               overrides_path=args.overrides_path)
    for error in result["errors"]:
        print(f"  [FAIL] {error}")
    print("SLICE_IDENTITY_RESULT: %s" % ("PASS" if result["passed"] else "FAIL"))
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
