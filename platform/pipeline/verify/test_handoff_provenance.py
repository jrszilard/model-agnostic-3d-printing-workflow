        far = struct.pack("<12fH", 0, 0, 1, 9, 0, 0, 9, 1, 0, 9, 0, 1, 0)
        near = struct.pack("<12fH", 0, 0, 1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0)
