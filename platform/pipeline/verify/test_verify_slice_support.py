import os
import subprocess
import tempfile
import unittest


HERE = os.path.dirname(os.path.abspath(__file__))
VERIFY = os.path.join(HERE, "verify-slice.sh")
POST = os.path.realpath(os.path.join(HERE, "..", "slice", "postprocess.py"))
SLICE_IDENTITY = os.path.realpath(os.path.join(HERE, "..", "slice", "slice_identity.py"))


HEADER = """; generated by PrusaSlicer test
M104 S210
M140 S60
M83
;LAYER_CHANGE
G1 Z0.20
;TYPE:Perimeter
G1 X10 Y10 E1
{support}
;LAYER_CHANGE
G1 Z0.40
;TYPE:Perimeter
G1 X20 Y20 E1
; prusaslicer_config = begin
; layer_height = 0.2
; prusaslicer_config = end
"""
SUPPORT = """;TYPE:Support material
G1 X12 Y12 E0.2
"""


class VerifySliceSupportIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.td = tempfile.TemporaryDirectory(); self.addCleanup(self.td.cleanup)
        self.out = self.td.name
        self.gcode = os.path.join(self.out, "plate_1.gcode")
        with open(os.path.join(self.out, "slice_exit.txt"), "w") as stream:
            stream.write("0\n")
        with open(os.path.join(self.out, "plate.3mf"), "wb") as stream:
            stream.write(b"3mf")
        with open(os.path.join(self.out, ".overrides.ini"), "w") as stream:
            stream.write("binary_gcode = 0\n")

    def write_plate(self, support=""):
        with open(self.gcode, "w") as stream:
            stream.write(HEADER.format(support=support))
        subprocess.run(["python3", POST, "--gcode", self.gcode,
                        "--manifest", os.path.join(self.out, "gcode_manifest.json")], check=True,
                       stdout=subprocess.PIPE, text=True)
        subprocess.run([
            "python3", SLICE_IDENTITY, "write",
            "--meta", os.path.join(self.out, "slice_meta.json"),
            "--gcode", self.gcode, "--project", os.path.join(self.out, "plate.3mf"),
            "--overrides", os.path.join(self.out, ".overrides.ini"),
            "--slicer", "prusa-slicer", "--machine", "test-machine",
            "--process", "test-process", "--filament", "test-filament",
            "--support-requested"], check=True, stdout=subprocess.PIPE, text=True)

    def verify(self):
        return subprocess.run([VERIFY, self.out], text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT)

    def test_zero_support_fails_and_removes_stale_handoff(self):
        self.write_plate()
        with open(os.path.join(self.out, "handoff.txt"), "w") as stream:
            stream.write("stale\n")
        result = self.verify()
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn("zero support extrusion", result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.out, "handoff.txt")))

    def test_support_extrusion_passes(self):
        self.write_plate(SUPPORT)
        result = self.verify()
        self.assertEqual(result.returncode, 0, result.stdout)
        with open(os.path.join(self.out, "verify_slice.txt")) as stream:
            self.assertEqual(stream.read().strip(), "PASS")

    def test_future_plate_cannot_drop_failed_hook_manifest_and_claim_legacy(self):
        self.write_plate(SUPPORT)
        os.remove(os.path.join(self.out, "gcode_manifest.json"))
        result = self.verify()
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn("MISSING gcode_manifest.json", result.stdout)


if __name__ == "__main__":
    unittest.main()
