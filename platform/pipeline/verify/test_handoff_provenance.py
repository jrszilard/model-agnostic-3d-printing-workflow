def qualify_spec(body):
    """Add the forward-only contract to fixtures whose test concern lies elsewhere."""
    doc = yaml.safe_load(body) or {}
    doc.setdefault("status", "draft")
    doc.setdefault("design", {"schema": 1, "mode": "originate",
                              "purpose": "exercise the handoff contract", "references": []})
    for dimension in doc.get("dimensions", []):
        if isinstance(dimension, dict):
            dimension.setdefault("reference", "originate")
    doc.setdefault("acceptance", {"printed": ["physical_check"]})
    return yaml.safe_dump(doc, sort_keys=False)


def ensure_future_plate(out):
    """Give a handoff fixture real git + slicer identity without weakening the production path."""
    root = os.path.dirname(out)
    if subprocess.run(["git", "-C", root, "rev-parse", "--show-toplevel"],
                      stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode:
        subprocess.run(["git", "init", "-q", root], check=True)
        subprocess.run(["git", "-C", root, "config", "user.email", "test@example.com"], check=True)
        subprocess.run(["git", "-C", root, "config", "user.name", "Test"], check=True)
        subprocess.run(["git", "-C", root, "commit", "--allow-empty", "-qm", "fixture"], check=True)
    ignore = os.path.join(root, ".gitignore")
    existing = Path(ignore).read_text() if os.path.isfile(ignore) else ""
    if "build/\n" not in existing:
        Path(ignore).write_text(existing + "build/\n")
    gcode = os.path.join(out, "plate_1.gcode")
    if os.path.isfile(gcode):
        inventory_fixture(Path(out))  # real synthetic inventory/project/moves before binding the test slice
    project = os.path.join(out, "plate.3mf")
    overrides = os.path.join(out, ".overrides.ini")
    if not os.path.isfile(project):
        with open(project, "wb") as stream: stream.write(b"3mf")
    with open(overrides, "w") as stream: stream.write("binary_gcode = 0\n")
    if os.path.isfile(gcode):
        subprocess.run(["python3", POSTPROCESS, "--gcode", gcode, "--manifest",
                        os.path.join(out, "gcode_manifest.json")],
                       check=True, stdout=subprocess.PIPE, text=True)
        subprocess.run([
            "python3", SLICE_IDENTITY, "write", "--meta", os.path.join(out, "slice_meta.json"),
            "--gcode", gcode, "--project", project, "--overrides", overrides,
            "--slicer", "prusa-slicer", "--machine", "test-machine",
            "--process", "test-process", "--filament", "test-filament"],
            check=True, stdout=subprocess.PIPE, text=True)
    for spec in Path(root).rglob('spec.yaml'):
        if not spec.is_relative_to(Path(out)):
            fixture_producer(root, spec.parent)
    # Future physical evidence must identify a commit, not a dirty source tree. These are synthetic
    # repositories, so checkpoint the fixture exactly as a real `bench.sh save` would. Ignored draft
    # geometry deliberately remains ignored for the next-touch primary-artifact regression.
    subprocess.run(["git", "-C", root, "add", "-A"], check=True)
    if subprocess.run(["git", "-C", root, "diff", "--cached", "--quiet"]).returncode:
        subprocess.run(["git", "-C", root, "commit", "-qm", "fixture state"], check=True)


def write_verdict(part_dir, models, verdict="PASS", step="step/thing.step", stls=None):
    """The verify.stamp verify.sh records: the verdict, the STEP it read, and the geom id of every
    STL the part held. `models` are paths relative to part_dir; `stls` overrides the id rows so a
    test can hand the gate a well-formed record that names other geometry."""
    if stls is None:
        stls = []
        for rel in models:
            with open(os.path.join(part_dir, rel), "rb") as stream:
                stls.append("stl=%s %s" % (hashlib.sha256(stream.read()).hexdigest()[:8], rel))
    body = ["geom=aaaaaaaa", "sha256=" + "a" * 64,
            "source=" + os.path.join(part_dir, step), "version=test",
            "verdict=" + verdict, "step=" + step, "stls=%d" % len(stls)] + stls
    with open(os.path.join(part_dir, "verify.stamp"), "w") as stream:
        stream.write("\n".join(body) + "\n")


def write_stl(path, body=STL):
    """An STL on disk in canonical form, returning its full sha256 — the geom id is its first 8."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode, payload = ("wb", body) if isinstance(body, bytes) else ("w", body)
    with open(path, mode) as stream:
        stream.write(payload)
    subprocess.run(["python3", C14N, path], check=True, stdout=subprocess.PIPE)
    with open(path, "rb") as stream:
        return hashlib.sha256(stream.read()).hexdigest()


