import hashlib
import json
import os
import stat
import subprocess
import tempfile
import unittest


HERE = os.path.dirname(os.path.abspath(__file__))
SLICE = os.path.join(HERE, "slice.sh")
POST = os.path.join(HERE, "postprocess.py")


GCODE = """; generated by PrusaSlicer
M104 S210
M140 S60
M83
;LAYER_CHANGE
G1 Z0.2
;TYPE:Perimeter
G1 X10 Y10 E1
;LAYER_CHANGE
G1 Z0.4
G1 X20 Y20 E1
; prusaslicer_config = begin
; layer_height = 0.2
; printer_model = COREONE
; prusaslicer_config = end
"""
STL = """solid test
facet normal 0 0 1
 outer loop
  vertex 0 0 0
  vertex 1 0 0
  vertex 0 1 0
 endloop
endfacet
endsolid test
"""


class SlicePipelineIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.td = tempfile.TemporaryDirectory(); self.addCleanup(self.td.cleanup)
        self.out = os.path.join(self.td.name, "build")
        self.stl = os.path.join(self.td.name, "part.stl")
        self.spec = os.path.join(self.td.name, "spec.yaml")
        self.fake = os.path.join(self.td.name, "prusa-slicer")
        self.hook = os.path.join(self.td.name, "hook.py")
        with open(self.stl, "w") as stream: stream.write(STL)
        with open(self.spec, "w") as stream: stream.write("part_id: test/part\n")
        with open(self.fake, "w") as stream:
            stream.write("#!/usr/bin/env bash\nset -eu\nout=''\nmode=''\n"
                         "while [ $# -gt 0 ]; do\n"
                         " case \"$1\" in --output) shift; out=$1;;"
                         " --export-gcode) mode=gcode;; --export-3mf) mode=3mf;; esac; shift; done\n"
                         "if [ \"$mode\" = gcode ]; then cat >\"$out\" <<'EOF'\n" + GCODE +
                         "EOF\nelse printf 3mf >\"$out\"; fi\n")
        os.chmod(self.fake, os.stat(self.fake).st_mode | stat.S_IXUSR)
        with open(self.hook, "w") as stream:
            stream.write("import sys\nwith open(sys.argv[1], 'a') as output:\n"
                         "    output.write(';POSTED\\n')\n")

    def run_slice(self, hook=None):
        os.makedirs(self.out, exist_ok=True)
        for stale in ("handoff.txt", "qualification_manifest.json", "verify_slice.txt"):
            with open(os.path.join(self.out, stale), "w") as stream: stream.write("stale\n")
        env = os.environ.copy(); env.update(PRUSA_SLICER=self.fake, OPENSCAD="/bin/false")
        command = [SLICE, "--support", "--spec", self.spec]
        if hook: command += ["--post", hook]
        command += [self.out, self.stl]
        return subprocess.run(command, env=env, text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT)

    def test_slice_records_intent_hook_and_final_identity(self):
        result = self.run_slice(self.hook)
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertFalse(os.path.exists(os.path.join(self.out, "handoff.txt")))
        self.assertFalse(os.path.exists(os.path.join(self.out, "qualification_manifest.json")))
        with open(os.path.join(self.out, "slice_meta.json")) as stream: meta = json.load(stream)
        self.assertEqual(meta["schema"], 2)
        self.assertTrue(meta["support_requested"])
        self.assertEqual(meta["spec"], os.path.realpath(self.spec))
        self.assertEqual(meta["profiles"]["machine"], "Prusa CORE One HF0.4 nozzle")
        self.assertEqual(meta["slicer"]["reported_by_gcode"], "PrusaSlicer")
        with open(os.path.join(self.out, "plate_1.gcode"), "rb") as stream:
            self.assertEqual(meta["artifacts"]["gcode_sha256"],
                             hashlib.sha256(stream.read()).hexdigest())
        manifest = os.path.join(self.out, "gcode_manifest.json")
        check = subprocess.run(["python3", POST, "--check", "--gcode",
                                os.path.join(self.out, "plate_1.gcode"), "--manifest", manifest],
                               text=True, stdout=subprocess.PIPE)
        self.assertEqual(check.returncode, 0, check.stdout)
        with open(os.path.join(self.out, "plate_1.gcode")) as stream:
            self.assertIn(";POSTED", stream.read())
        self.assertTrue(os.path.exists(os.path.join(self.out, "plate_geom.txt")))

    def test_failed_post_hook_fails_slice_and_records_manifest(self):
        with open(self.hook, "w") as stream: stream.write("raise SystemExit(6)\n")
        result = self.run_slice(self.hook)
        self.assertEqual(result.returncode, 1, result.stdout)  # postprocess normalises to gate failure
        with open(os.path.join(self.out, "gcode_manifest.json")) as stream:
            self.assertFalse(json.load(stream)["passed"])


if __name__ == "__main__":
    unittest.main()
