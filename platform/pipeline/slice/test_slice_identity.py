import copy
import hashlib
import json
import os
import tempfile
import unittest

import slice_identity as si


GCODE = b"""; generated by PrusaSlicer 2.9.6
G1 X0 Y0
; prusaslicer_config = begin
; layer_height = 0.2
; printer_model = COREONE
; prusaslicer_config = end
"""


class SliceIdentityTests(unittest.TestCase):
    def setUp(self):
        self.td = tempfile.TemporaryDirectory(); self.addCleanup(self.td.cleanup)
        self.gcode = os.path.join(self.td.name, "plate_1.gcode")
        self.project = os.path.join(self.td.name, "plate.3mf")
        self.overrides = os.path.join(self.td.name, ".overrides.ini")
        self.hook = os.path.join(self.td.name, "hook.py")
        self.meta = os.path.join(self.td.name, "slice_meta.json")
        with open(self.gcode, "wb") as stream: stream.write(GCODE)
        with open(self.project, "wb") as stream: stream.write(b"3MF")
        with open(self.overrides, "wb") as stream: stream.write(b"binary_gcode = 0\n")
        with open(self.hook, "wb") as stream: stream.write(b"print('hook')\n")

    def build(self):
        return si.build_metadata(
            gcode=self.gcode, project=self.project, overrides_path=self.overrides,
            slicer="prusa-slicer", machine="Core One", process="0.20 SPEED",
            filament="PLA", rotation={"x": 90, "y": 0, "z": 0},
            support_requested=True, spec=None, overrides=["fill_density=20%"],
            post_hooks=[self.hook])

    def evaluate(self, data):
        return si.evaluate(data, gcode=self.gcode, project=self.project,
                           overrides_path=self.overrides)

    def test_records_profiles_effective_config_and_every_artifact_hash(self):
        data = self.build()
        self.assertTrue(self.evaluate(data)["passed"])
        self.assertEqual(data["schema"], 2)
        self.assertEqual(data["profiles"]["machine"], "Core One")
        self.assertEqual(data["rotation"]["x"], 90.0)
        self.assertEqual(data["artifacts"]["gcode_sha256"],
                         hashlib.sha256(GCODE).hexdigest())
        self.assertEqual(data["artifacts"]["effective_config_sha256"],
                         hashlib.sha256(si.embedded_config_bytes(self.gcode)).hexdigest())
        self.assertEqual(data["post_hooks"][0]["sha256"], si.sha256_file(self.hook))

    def test_final_gcode_change_fails(self):
        data = self.build()
        with open(self.gcode, "ab") as stream: stream.write(b"; changed\n")
        result = self.evaluate(data)
        self.assertFalse(result["passed"])
        self.assertTrue(any("changed after slice metadata" in e for e in result["errors"]))

    def test_effective_config_hash_cannot_be_swapped_while_gcode_hash_is_updated(self):
        data = self.build()
        changed = GCODE.replace(b"layer_height = 0.2", b"layer_height = 0.3")
        with open(self.gcode, "wb") as stream: stream.write(changed)
        data["artifacts"]["gcode_sha256"] = hashlib.sha256(changed).hexdigest()
        result = self.evaluate(data)
        self.assertFalse(result["passed"])
        self.assertIn("effective embedded slicer configuration changed", result["errors"])

    def test_profile_name_or_rotation_may_not_be_missing(self):
        data = self.build(); data["profiles"]["filament"] = ""
        data["rotation"]["z"] = float("nan")
        result = self.evaluate(data)
        self.assertFalse(result["passed"])
        self.assertIn("profiles.filament is missing", result["errors"])
        self.assertIn("rotation.z must be finite", result["errors"])

    def test_post_hook_change_fails(self):
        data = self.build()
        with open(self.hook, "a") as stream: stream.write("# moved\n")
        result = self.evaluate(data)
        self.assertFalse(result["passed"])
        self.assertTrue(any("post hook changed" in e for e in result["errors"]))

    def test_incomplete_or_absent_embedded_config_is_refused(self):
        with open(self.gcode, "wb") as stream:
            stream.write(b"; generated by PrusaSlicer 2.9.6\n; prusaslicer_config = begin\n")
        with self.assertRaisesRegex(ValueError, "embedded-config"):
            self.build()

    def test_write_and_load_round_trip(self):
        si.write_metadata(
            self.meta, gcode=self.gcode, project=self.project,
            overrides_path=self.overrides, slicer="prusa-slicer", machine="Core One",
            process="0.20 SPEED", filament="PLA",
            rotation={"x": 0, "y": 0, "z": 0}, support_requested=False,
            spec=None, overrides=[], post_hooks=[])
        self.assertTrue(si.load_and_evaluate(
            self.meta, gcode=self.gcode, project=self.project,
            overrides_path=self.overrides)["passed"])



class ColourRegionTests(SliceIdentityTests):
    def build_coloured(self):
        self.region = os.path.join(self.td.name, "line.stl")
        with open(self.region, "wb") as stream: stream.write(b"solid line\n")
        return si.build_metadata(
            gcode=self.gcode, project=self.project, overrides_path=self.overrides,
            slicer="prusa-slicer", machine="Core One", process="0.20 SPEED",
            filament="PLA", rotation={"x": 0, "y": 0, "z": 0},
            support_requested=False, spec=None, overrides=[], post_hooks=[],
            colour_regions=[self.region + "=2"])

    def test_region_is_bound_and_rehashed(self):
        data = self.build_coloured()
        self.assertEqual(data["colour_regions"][0]["filament"], 2)
        paths = dict(gcode=self.gcode, project=self.project, overrides_path=self.overrides)
        self.assertTrue(si.evaluate(data, **paths)["passed"])
        with open(self.region, "ab") as stream: stream.write(b"moved")
        result = si.evaluate(data, **paths)
        self.assertFalse(result["passed"])
        self.assertTrue(any("colour region changed" in e for e in result["errors"]))

    def test_metadata_without_regions_still_passes(self):
        data = self.build_coloured()
        del data["colour_regions"]
        paths = dict(gcode=self.gcode, project=self.project, overrides_path=self.overrides)
        self.assertTrue(si.evaluate(data, **paths)["passed"])

    def test_missing_region_refuses_at_write(self):
        with self.assertRaises(ValueError):
            si.build_metadata(
                gcode=self.gcode, project=self.project, overrides_path=self.overrides,
                slicer="prusa-slicer", machine="Core One", process="0.20 SPEED",
                filament="PLA", rotation={"x": 0, "y": 0, "z": 0},
                support_requested=False, spec=None, overrides=[], post_hooks=[],
                colour_regions=[os.path.join(self.td.name, "nope.stl=2")])

if __name__ == "__main__":
    unittest.main()
