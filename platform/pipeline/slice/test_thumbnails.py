def png_dimensions(data):
    """Read width/height out of a PNG IHDR chunk."""
    assert data.startswith(b"\x89PNG\r\n\x1a\n"), "not a PNG"
    return struct.unpack(">II", data[16:24])

FIXTURE = os.path.join(os.path.dirname(__file__), "testdata", "gui_sliced_header.gcode")

PNG = b"\x89PNG\r\n\x1a\n" + bytes(range(256)) * 3

GCODE = (
    "; HEADER_BLOCK_START\n"
    "; generated by OrcaSlicer 2.4.1\n"
    "; total layer number: 100\n"
    "; HEADER_BLOCK_END\n"
    "\n"
    "; external perimeters extrusion width = 0.42mm\n"
    "G1 X10 Y10 F600\n"
)


class TestInjectPlacement(unittest.TestCase):
    def test_block_lands_between_the_header_and_the_first_gcode(self):
        out = inject_thumbnails(GCODE, [(4, 4, PNG)])

        self.assertIn("; thumbnail begin 4x4", out)
        self.assertLess(out.index("; HEADER_BLOCK_END"), out.index("; THUMBNAIL_BLOCK_START"))
        self.assertLess(out.index("; THUMBNAIL_BLOCK_END"), out.index("G1 X10 Y10 F600"))


class TestBlockFormat(unittest.TestCase):
    """The framing GUI-sliced gcode uses on this K1C. Moonraker parses on these exact tokens."""

    def test_declared_length_is_the_base64_char_count_not_the_decoded_size(self):
        out = inject_thumbnails(GCODE, [(4, 4, PNG)])

        declared = int(re.search(r"; thumbnail begin 4x4 (\d+)", out).group(1))
        self.assertEqual(declared, len(base64.b64encode(PNG)))
        self.assertNotEqual(declared, len(PNG))

    def test_payload_lines_are_comment_prefixed_and_wrapped_at_78_chars(self):
        out = inject_thumbnails(GCODE, [(4, 4, PNG)])

        lines = out.split("\n")
        i = next(k for k, ln in enumerate(lines) if ln.startswith("; thumbnail begin 4x4"))
        j = next(k for k, ln in enumerate(lines) if ln == "; thumbnail end")
        payload_lines = lines[i + 1:j]
        self.assertTrue(payload_lines, "expected at least one payload line")
        for ln in payload_lines:
            self.assertTrue(ln.startswith("; "), f"missing comment prefix: {ln!r}")
            self.assertLessEqual(len(ln), 80, f"line too wide: {len(ln)}")

    def test_a_thumbnail_survives_a_write_read_round_trip(self):
        out = inject_thumbnails(GCODE, [(96, 96, PNG), (300, 300, PNG[:64])])

        self.assertEqual(find_thumbnails(out), [(96, 96, PNG), (300, 300, PNG[:64])])

    def test_gcode_with_no_thumbnails_reads_back_empty(self):
        self.assertEqual(find_thumbnails(GCODE), [])


class TestParseSizes(unittest.TestCase):
    def test_reads_the_machine_presets_thumbnail_spec(self):
        self.assertEqual(parse_sizes(["96x96", "300x300"]), [(96, 96), (300, 300)])

    def test_rejects_a_malformed_size(self):
        with self.assertRaises(ValueError):
            parse_sizes(["96by96"])


class TestProductionSafety(unittest.TestCase):
    def test_injecting_twice_does_not_duplicate_the_block(self):
        once = inject_thumbnails(GCODE, [(4, 4, PNG)])
        twice = inject_thumbnails(once, [(4, 4, PNG)])

        self.assertEqual(twice.count("; THUMBNAIL_BLOCK_START"), 1)
        self.assertEqual(twice, once)

    def test_gcode_without_a_header_block_raises_a_clear_error(self):
        with self.assertRaises(ValueError) as ctx:
            inject_thumbnails("G1 X10 Y10\n", [(4, 4, PNG)])

        self.assertIn("HEADER_BLOCK_END", str(ctx.exception))


class TestMatchesRealGuiOutput(unittest.TestCase):
    """Golden test against gcode OrcaSlicer's GUI actually produced for this K1C."""

    def setUp(self):
        with open(FIXTURE) as f:
            self.gui = f.read()

    def test_reads_the_gui_thumbnail(self):
        thumbs = find_thumbnails(self.gui)

        self.assertEqual(len(thumbs), 1)
        w, h, png = thumbs[0]
        self.assertEqual((w, h), (96, 96))
        self.assertTrue(png.startswith(b"\x89PNG"))

    def test_our_injected_block_is_byte_identical_to_the_gui(self):
        _, _, png = find_thumbnails(self.gui)[0]
        stripped = strip_thumbnails(self.gui)
        self.assertNotIn("thumbnail", stripped)

        self.assertEqual(inject_thumbnails(stripped, [(96, 96, png)]), self.gui)


@unittest.skipUnless(shutil.which("openscad"), "openscad not installed")
class TestRender(unittest.TestCase):
    def test_renders_a_png_at_the_requested_size(self):
        with tempfile.TemporaryDirectory() as d:
            stl = os.path.join(d, "cube.stl")
            with open(stl, "w") as f:
                f.write(CUBE_STL)

            png = render_png([stl], 96, 96)

        self.assertEqual(png_dimensions(png), (96, 96))

    def test_rendered_thumbnail_survives_injection(self):
        with tempfile.TemporaryDirectory() as d:
            stl = os.path.join(d, "cube.stl")
            with open(stl, "w") as f:
                f.write(CUBE_STL)

            png = render_png([stl], 48, 48)

        out = inject_thumbnails(GCODE, [(48, 48, png)])
        self.assertEqual(find_thumbnails(out), [(48, 48, png)])


